"""Streamlit demo:  streamlit run app.py"""
from __future__ import annotations

import json

import pandas as pd
import streamlit as st

from copilot.config import DATA_DIR
from copilot.pipeline import LeadCopilot
from copilot.schemas import Lead

st.set_page_config(page_title="Cynbit Lead-to-Proposal Copilot", page_icon="📨", layout="wide")
SAMPLES = json.loads((DATA_DIR / "sample_leads.json").read_text(encoding="utf-8")) + \
          json.loads((DATA_DIR / "holdout_leads.json").read_text(encoding="utf-8"))
TIER_ICON = {"HOT": "🔴", "WARM": "🟠", "COLD": "🔵", "NOT_A_PROSPECT": "⚪"}


@st.cache_resource
def get_copilot(use_llm: bool) -> LeadCopilot:
    return LeadCopilot(use_llm=use_llm)


with st.sidebar:
    st.header("Settings")
    use_llm = st.toggle("Use LLM if an API key is configured", value=True)
    copilot = get_copilot(use_llm)
    st.caption(f"Active engine: **{copilot.provider}**")
    st.caption("Offline mode = rules + TF-IDF retrieval + templates. No data leaves this machine.")
    st.divider()
    st.caption("All sample leads are synthetic. Company facts come from the public cynbit.in website.")

st.title("📨 Lead-to-Proposal AI Copilot")
st.caption("Triage an inbound enquiry in seconds: classify → score → ground in Cynbit's portfolio → draft a reply for human review.")
tab_single, tab_batch = st.tabs(["Single lead", "Batch triage"])

with tab_single:
    labels = ["(write your own)"] + [f"{s['id']} - {s['lead']['company'] or s['lead']['name']}" for s in SAMPLES]
    pick = st.selectbox("Load a sample lead", labels)
    base = SAMPLES[labels.index(pick) - 1]["lead"] if pick != labels[0] else {"name": "", "company": "", "email": "", "message": ""}
    c1, c2, c3 = st.columns(3)
    name = c1.text_input("Name", base["name"], key=f"n{pick}")
    company = c2.text_input("Company", base["company"], key=f"c{pick}")
    email = c3.text_input("Email", base["email"], key=f"e{pick}")
    message = st.text_area("Message", base["message"], height=120, key=f"m{pick}")
    if st.button("Run copilot", type="primary", disabled=not message.strip()):
        res = copilot.process(Lead(name=name, company=company, email=email, message=message))
        ex, sc = res.extraction, res.score
        m1, m2, m3, m4 = st.columns(4)
        m1.metric("Tier", f"{TIER_ICON[sc.tier.value]} {sc.tier.value}")
        m2.metric("Score", f"{sc.score}/100")
        m3.metric("Intent", ex.intent.value)
        m4.metric("Route to", sc.route.value)
        st.info(f"**SLA:** {sc.recommended_sla}")
        left, right = st.columns(2)
        with left:
            st.subheader("Understanding")
            st.json({"service_line": ex.service_line.value, "industry": ex.industry, "budget": ex.budget_text,
                     "timeline": ex.timeline_text, "urgency": ex.urgency.value, "language": ex.language,
                     "requirements": ex.requirements})
            st.subheader("Why this score")
            st.dataframe(pd.DataFrame([c.model_dump() for c in sc.components]), hide_index=True, width="stretch")
            for n in sc.notes:
                st.warning(n)
        with right:
            st.subheader("Grounding evidence")
            for e in res.evidence:
                st.markdown(f"- **{e.title}** `{e.type}` · similarity {e.score}  \n  {e.url}")
            st.subheader("Draft reply (human review required)")
            if res.proposal:
                st.text_input("Subject", res.proposal.subject)
                st.text_area("Body", res.proposal.body, height=300)
                st.caption(f"Generated by: {res.proposal.generated_by}")
                for n in res.proposal.guardrail_notes:
                    st.warning(n)
                with st.expander("Discovery-call questions"):
                    for q in res.proposal.discovery_questions:
                        st.markdown(f"- {q}")
            else:
                st.write("No reply drafted - this message is not a sales prospect.")
        with st.expander("Pipeline trace"):
            st.dataframe(pd.DataFrame([t.model_dump() for t in res.trace]), hide_index=True, width="stretch")

with tab_batch:
    st.write("Triage every sample lead and rank the sales queue by score.")
    if st.button("Run batch"):
        rows = []
        for s in SAMPLES:
            r = copilot.process(Lead(**s["lead"]))
            rows.append({"id": s["id"], "who": s["lead"]["company"] or s["lead"]["name"], "tier": r.score.tier.value,
                         "score": r.score.score, "intent": r.extraction.intent.value,
                         "service": r.extraction.service_line.value, "route": r.score.route.value})
        st.dataframe(pd.DataFrame(rows).sort_values("score", ascending=False), hide_index=True, width="stretch")
